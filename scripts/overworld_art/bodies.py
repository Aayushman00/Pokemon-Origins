BACK = {"u": "t"}  # no shirt opening from behind


def _views(down, arms_up, left, left_arm_up):
    """{direction: {frame: (body_layer, overlay_layer_or_None)}}."""
    up = {k: swap(v, BACK) for k, v in down.items()}
    out = {}
    for name, src in (("down", down), ("up", up)):
        out[name] = {
            "stand": (src["stand"], None),
            "stepA": (src["stepA"], None),
            "stepB": (mirror(src["stepA"]), None),
            "alert": (src["alert"], arms_up),
        }
    out["left"] = {
        "stand": (left["stand"], None),
        "stepA": (left["stepA"], None),
        "stepB": (left["stepB"], None),
        "alert": (left["alert"], left_arm_up),
    }
    return out


