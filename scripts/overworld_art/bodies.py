def _hero_views(down, up, left):
    views = {}
    for name, poses, arms in (("down", down, HERO_ARMS_UP), ("up", up, HERO_ARMS_UP),
                              ("left", left, HERO_LEFT_ARM_UP)):
        dx = _SIDE_SHIFT[name]
        move = (lambda layer: _nudge(layer, dx)) if dx else (lambda layer: layer)
        views[name] = {k: (move(v), move(arms) if k == "alert" else None) for k, v in poses.items()}
    return views


