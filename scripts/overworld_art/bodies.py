def _nudge(layer, dx):
    """Shift a layer dx pixels sideways (never pushing art off the cell)."""
    top, rows = layer
    if dx > 0:
        assert all(r.endswith("." * dx) for r in rows), "nudge would clip the art"
        return top, ["." * dx + r[:-dx] for r in rows]
    assert all(r.startswith("." * -dx) for r in rows), "nudge would clip the art"
    return top, [r[-dx:] + "." * -dx for r in rows]


