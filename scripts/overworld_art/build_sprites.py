"""Export the whole cast for the game and the React UI.

Writes:
  frontend/public/sprites/overworld/<id>.png      128x128 sheet per character
  frontend/public/sprites/overworld/master_palette.json
  frontend/public/sprites/overworld/manifest.json   (read by /sprite-preview.html)
  frontend/src/v2/overworld/render/sheets.generated.js   sheet manifest
  frontend/src/v2/ui/trainerArt.generated.js      front-facing art for PixelTrainer

Usage (from the repo root): python3 -m scripts.overworld_art.build_sprites
"""
import json
from pathlib import Path

from .characters import ROSTER
from .compose import ramp_for
from .palette import OUTLINE, RAMPS, WHITE
from .sheets import COLUMNS, ROWS, build_sheet, frame_keys

ROOT = Path(__file__).resolve().parents[2]
SPRITES = ROOT / "frontend" / "public" / "sprites" / "overworld"
SHEETS_JS = ROOT / "frontend" / "src" / "v2" / "overworld" / "render" / "sheets.generated.js"
TRAINER_JS = ROOT / "frontend" / "src" / "v2" / "ui" / "trainerArt.generated.js"
INDEX = "0123456789abcdefghijklmnopqrstuvwxyz"
HEADER = "// Generated by scripts/overworld_art/build_sprites.py - do not edit by hand.\n"


def ui_art(char):
    """Down-facing stand frame (trimmed to its top) as palette-indexed rows,
    plus which palette indices belong to the top so the UI can tint it."""
    keys = frame_keys(char, "down", "stand")
    pal, top, rows = [], {}, []
    lookup = {}
    top_row = next(y for y in range(32) if any(k is not None for k in keys[y]))
    for y in range(top_row, 32):
        line = ""
        for key in keys[y]:
            if key is None:
                line += "."
                continue
            if key == "outline":
                col, tone = OUTLINE, None
            elif key == "white":
                col, tone = WHITE, None
            elif isinstance(key, str):
                col, tone = key, None
            else:
                m, tone = key
                ramp = ramp_for(char["mats"], m)
                col = {"hi": ramp[0], "base": ramp[-2] if len(ramp) > 1 else ramp[0], "shadow": ramp[-1]}[tone]
            if col not in lookup:
                lookup[col] = len(pal)
                pal.append(col)
            i = lookup[col]
            if key not in ("outline", "white") and key[0] == "t":
                top[INDEX[i]] = tone
            line += INDEX[i]
        rows.append(line)
    return {"rows": rows, "pal": pal, "top": top}


def main():
    SPRITES.mkdir(parents=True, exist_ok=True)
    for char in ROSTER:
        build_sheet(char).save(SPRITES / f"{char['id']}.png")
    palette = {
        "outline": OUTLINE,
        "white": WHITE,
        "ramps": RAMPS,
        "characters": {c["id"]: c["mats"] for c in ROSTER},
    }
    (SPRITES / "master_palette.json").write_text(json.dumps(palette, indent=2) + "\n")

    manifest = [{"id": c["id"], "label": c["label"], "gender": c["gender"]} for c in ROSTER]
    (SPRITES / "manifest.json").write_text(json.dumps({"columns": COLUMNS, "rows": ROWS, "sheets": manifest}, indent=1) + "\n")
    SHEETS_JS.write_text(
        HEADER
        + f"// Sheet layout: {len(COLUMNS)} columns ({', '.join(COLUMNS)}) x {len(ROWS)} rows ({', '.join(ROWS)}), 16x32 cells.\n"
        + f"export const SHEETS = {json.dumps(manifest, indent=1)};\n\n"
        + "export const SHEET_NAMES = SHEETS.map((s) => s.id);\n"
    )
    art = {c["id"]: ui_art(c) for c in ROSTER}
    TRAINER_JS.write_text(HEADER + f"export const TRAINER_ART = {json.dumps(art, separators=(',', ':'))};\n")
    print(f"wrote {len(ROSTER)} sheets to {SPRITES.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
