"""Empty rows under every battle sprite, so each one stands on its oval.

  python3 -m scripts.overworld_art.battle_seats

Writes frontend/src/sprites/battleSeats.generated.js: dex -> [front, back].
Rerun it whenever a sprite under frontend/public/sprites/battle changes.
"""
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SPRITES = ROOT / "frontend" / "public" / "sprites" / "battle"
OUT = ROOT / "frontend" / "src" / "sprites" / "battleSeats.generated.js"


def rows_below(path):
    with Image.open(path) as img:
        rgba = img.convert("RGBA")
    return rgba.height - rgba.getbbox()[3]


def seats():
    dexes = sorted(int(d.name) for d in SPRITES.iterdir() if d.name.isdigit())
    return {n: [rows_below(SPRITES / f"{n:03d}" / f"{side}.png") for side in ("front", "back")] for n in dexes}


def render():
    return ("// Generated by scripts/overworld_art/battle_seats.py. Do not edit.\n"
            "// dex -> [empty rows under the front sprite, under the back sprite], of 64.\n"
            f"export const BATTLE_SEATS = {json.dumps(seats(), separators=(',', ':'))};\n")


if __name__ == "__main__":
    OUT.write_text(render())
    print(f"wrote {OUT.name}")
