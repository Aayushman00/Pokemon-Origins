#!/usr/bin/env node
// npm run validate:maps  checks every map and that the server index is current.
// npm run maps:index     validates, then rewrites the server index and the client's puzzle engine.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { serverIndex, validateMaps } from "../frontend/src/v2/overworld/maps/pipeline.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const MAPS_DIR = join(ROOT, "frontend/public/maps");
const INDEX_FILE = join(ROOT, "backend/data/world/maps.index.json");
const PUZZLE_FILE = join(ROOT, "frontend/src/v2/overworld/logic/puzzles.generated.js");

const raw = {};
for (const file of readdirSync(MAPS_DIR).filter((f) => f.endsWith(".json"))) {
	raw[file.replace(/\.json$/, "")] = JSON.parse(readFileSync(join(MAPS_DIR, file), "utf8"));
}

const names = JSON.parse(readFileSync(join(ROOT, "backend/data/world/names.json"), "utf8"));
const errors = validateMaps(raw, { imageExists: (image) => existsSync(join(MAPS_DIR, image)), names });
if (errors.length) {
	for (const e of errors) console.error(`  ${e}`);
	console.error(`validate:maps failed: ${errors.length} problem(s) in ${Object.keys(raw).length} maps`);
	process.exit(1);
}

const index = `${JSON.stringify(serverIndex(raw), null, "\t")}\n`;
// The client walks the same rules replay() checks, so it gets a copy of the
// engine: frontend/ is its own Docker build context and can't import backend/.
const lf = (s) => s.replace(/\r\n/g, "\n");
const specs = JSON.parse(readFileSync(join(ROOT, "backend/data/gyms/gym_puzzles.json"), "utf8"));
const puzzles = `// Generated by npm run maps:index from backend/src/gyms/puzzles.js. Do not edit.
${lf(readFileSync(join(ROOT, "backend/src/gyms/puzzles.js"), "utf8"))}
export const GYM_PUZZLES = ${JSON.stringify(specs)};
export default AP;
`;
if (process.argv.includes("--write")) {
	mkdirSync(dirname(INDEX_FILE), { recursive: true });
	writeFileSync(INDEX_FILE, index);
	writeFileSync(PUZZLE_FILE, puzzles);
	console.log(`wrote ${INDEX_FILE}`);
} else {
	for (const [file, want] of [[INDEX_FILE, index], [PUZZLE_FILE, puzzles]]) {
		if (!existsSync(file) || lf(readFileSync(file, "utf8")) !== want) {
			console.error(`validate:maps failed: ${file} is stale, run npm run maps:index`);
			process.exit(1);
		}
	}
}
console.log(`validate:maps ok: ${Object.keys(raw).length} maps`);
